/* miiimg core (portable): the Mii face-image database (nn::mii image database) and a minimal image generator.
 * The database lives in memory for the life of the process: an image the title did not store is generated again when asked for (the console keeps JPEG files, the host has
 * no use for the persistence). Each entry has a 0x20-byte attribute record {u8 unique id[16], u32 width, u32 height, u32 image size, u32 flags}; the layouts are the author's
 * reading of the public description (unverified on a console). */
#pragma once
#include <stddef.h>
#include <stdint.h>

#define MIIIMG_CAPACITY 100u
#define MIIIMG_ATTR_SIZE 0x20u
#define MIIIMG_MAX_IMAGE 0x20000u
#define MIIIMG_GEN_SIZE 96 /* generated images are 96x96 */
typedef struct {
    uint8_t uid[16];
    uint32_t width, height, size, flags; /* flags bit 0: generated by the host, not supplied by the title */
    uint8_t *data;
} MiiImgEntry;
typedef struct {
    MiiImgEntry e[MIIIMG_CAPACITY];
    unsigned count;
    MiiImgEntry m[MIIIMG_CAPACITY]; /* the migration store (commands 18-20): images staged by AddImageForMigration, merged into `e` by SaveHeaderForMigration */
    unsigned mcount;
    int initialized;
} MiiImgDb;

void miiimg_init(MiiImgDb *d); /* empties the database and frees every image */
unsigned miiimg_count(const MiiImgDb *d);
unsigned miiimg_free_slots(const MiiImgDb *d);
/* Stores `image` (n bytes, a JPEG) for `uid`, replacing the entry with that id; with n == 0 a face image is generated. Returns the entry index, or -1 when the database is full
 * (new id only) or the image is larger than MIIIMG_MAX_IMAGE. */
int miiimg_add(MiiImgDb *d, const uint8_t uid[16], const void *image, size_t n);
int miiimg_find(const MiiImgDb *d, const uint8_t uid[16]); /* index or -1 */
int miiimg_delete_index(MiiImgDb *d, unsigned index);      /* 0 or -1; later entries move down */
void miiimg_attribute(const MiiImgEntry *e, uint8_t out[MIIIMG_ATTR_SIZE]);
/* A deterministic 96x96 baseline JPEG face for `uid` (skin tone, hair colour, eyes and mouth derived from the id). malloc'd; NULL on failure. */
uint8_t *miiimg_generate(const uint8_t uid[16], size_t *out_size);
/* Migration store (miiimg 18 AddImageForMigration, 19 ClearHeaderForMigration, 20 SaveHeaderForMigration): a staging table keyed by the same unique id as the
 * database. Add behaves like miiimg_add on the staging table (-1: full or oversized); clear empties it; save merges every staged image into the database (an existing id is
 * replaced) and empties the staging table, or returns -1 and changes nothing when the new ids do not fit. */
unsigned miiimg_migration_count(const MiiImgDb *d);
int miiimg_migration_add(MiiImgDb *d, const uint8_t uid[16], const void *image, size_t n);
void miiimg_migration_clear(MiiImgDb *d);
int miiimg_migration_save(MiiImgDb *d);
