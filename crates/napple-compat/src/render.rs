//! Markdown rendering of the matrix (COMPATIBILITY.md). Deterministic: same matrix -> same text.
use crate::model::*;
use std::fmt::Write;

fn short(s: &str) -> &str {
    &s[..s.len().min(16)]
}

fn esc(s: &str) -> String {
    s.replace('|', "\\|").replace('\n', " ")
}

pub fn render(m: &Matrix) -> String {
    let mut o = String::new();
    let _ = writeln!(o, "# Napple compatibility matrix\n");
    let _ = writeln!(o, "Generated by `napple compat render` from `compat/matrix.json`. Do not edit by hand; use `napple compat set`.");
    let _ = writeln!(o, "Metadata only: no game bytes, keys or firmware appear here. Format of stage results: `docs/compat-format.md`.\n");
    let last = if m.last_run == 0 { "never".to_string() } else { iso(m.last_run) };
    let _ = writeln!(o, "Last `compat run`: {last}\n");
    let _ = writeln!(o, "Legend: `OK` pass, `~` partial, `X` fail, `B` blocked, `.` untested.\n");
    let _ = write!(o, "| Game | Ver | Build id |");
    for s in STAGES {
        let _ = write!(o, " {s} |");
    }
    let _ = write!(o, "\n|---|---|---|");
    for _ in STAGES {
        let _ = write!(o, ":-:|");
    }
    let _ = writeln!(o);
    for g in &m.games {
        for v in &g.versions {
            let name = if g.name.is_empty() { g.title_id.clone() } else { format!("{} ({})", esc(&g.name), g.title_id) };
            let _ = write!(o, "| {name} | {}{} | `{}` |", v.version, if v.kind == "update" { " upd" } else { "" }, short(&v.build_id));
            for s in STAGES {
                let _ = write!(o, " {} |", v.stage(s).status.symbol());
            }
            let _ = writeln!(o);
        }
    }
    let _ = writeln!(o);
    cross_game(&mut o, m);
    for g in &m.games {
        detail(&mut o, g);
    }
    o
}

fn nso_set(v: &VersionEntry) -> Vec<&str> {
    v.modules.iter().map(|m| m.name.as_str()).collect()
}

fn cross_game(o: &mut String, m: &Matrix) {
    let rows: Vec<(String, &VersionEntry)> = m
        .games
        .iter()
        .filter_map(|g| g.versions.iter().find(|v| v.kind == "base" && v.npdm.is_some()).map(|v| (if g.name.is_empty() { g.title_id.clone() } else { g.name.clone() }, v)))
        .collect();
    if rows.len() < 2 {
        return;
    }
    let _ = writeln!(o, "## Cross-game comparison (base versions)\n");
    let _ = writeln!(o, "| Game | NSO modules | 64-bit | Main stack | System resource | Services used | Allowed SVCs |\n|---|---|:-:|---|---|---:|---:|");
    for (n, v) in &rows {
        let p = v.npdm.as_ref().unwrap();
        let _ = writeln!(
            o,
            "| {} | {} ({}) | {} | {:#x} | {:#x} | {} | {} |",
            esc(n),
            v.modules.len(),
            nso_set(v).join(", "),
            if p.is_64bit { "yes" } else { "no" },
            p.main_thread_stack_size,
            p.system_resource_size,
            p.services_used.len(),
            p.allowed_svcs.len()
        );
    }
    // Services needed by every game vs by only one: priorities for the runtime.
    let sets: Vec<std::collections::BTreeSet<&str>> = rows.iter().map(|(_, v)| v.npdm.as_ref().unwrap().services_used.iter().map(|s| s.as_str()).collect()).collect();
    let common: Vec<&str> = sets[0].iter().copied().filter(|s| sets.iter().all(|x| x.contains(s))).collect();
    let _ = writeln!(o, "\nServices requested by every game above ({}): {}\n", common.len(), common.iter().map(|s| format!("`{s}`")).collect::<Vec<_>>().join(", "));
}

fn detail(o: &mut String, g: &GameEntry) {
    let title = if g.name.is_empty() { "(name unknown)".to_string() } else { esc(&g.name) };
    let _ = writeln!(o, "## {title} `{}`\n", g.title_id);
    if !g.publisher.is_empty() {
        let _ = writeln!(o, "Publisher: {}\n", esc(&g.publisher));
    }
    if !g.dlc.is_empty() {
        let _ = writeln!(o, "DLC packs: {}\n", g.dlc.iter().map(|d| format!("`{}` v{}", d.title_id, d.version)).collect::<Vec<_>>().join(", "));
    }
    for n in &g.notes {
        let _ = writeln!(o, "- {}", esc(n));
    }
    for v in &g.versions {
        let _ = writeln!(o, "\n### {} v{} (build `{}`)\n", v.kind, v.version, short(&v.build_id));
        if !v.display_version.is_empty() {
            let _ = writeln!(o, "Display version: {}\n", esc(&v.display_version));
        }
        if !v.modules.is_empty() {
            let _ = writeln!(o, "| Module | Build id | .text bytes | svc | svc numbers | TPIDR(RO)_EL0 | CNT* | x18 | other sysreg |\n|---|---|---:|---:|---|---:|---:|---:|---:|");
            for mo in &v.modules {
                let c = |k: &str| mo.sites.get(k).copied().unwrap_or(0);
                let _ = writeln!(
                    o,
                    "| {} | `{}` | {} | {} | {} | {} | {} | {} | {} |",
                    mo.name,
                    short(&mo.build_id),
                    mo.text_bytes,
                    c("Svc"),
                    mo.svc_numbers.iter().map(|n| format!("{n:#x}")).collect::<Vec<_>>().join(" "),
                    c("MrsTpidrEl0") + c("MsrTpidrEl0") + c("MrsTpidrroEl0"),
                    c("MrsCntvct") + c("MrsCntpct") + c("MrsCntfrq"),
                    c("X18"),
                    c("OtherSysReg")
                );
            }
            let _ = writeln!(o);
        }
        if let Some(p) = &v.npdm {
            npdm(o, p);
        }
        let blockers: Vec<String> = STAGES
            .iter()
            .filter_map(|s| {
                let r = v.stage(s);
                (!matches!(r.status, Status::Pass | Status::Untested)).then(|| {
                    let ev = if r.evidence.is_empty() { String::new() } else { format!(" (evidence: `{}`)", r.evidence) };
                    format!("- `{s}`: {} - {}{ev}", r.status.name(), esc(&r.reason))
                })
            })
            .collect();
        if !blockers.is_empty() {
            let _ = writeln!(o, "Blockers and partial results:\n");
            for b in blockers {
                let _ = writeln!(o, "{b}");
            }
            let _ = writeln!(o);
        }
        let c = v.counters();
        if !c.is_empty() {
            let _ = writeln!(o, "Runtime counters:\n");
            if !c.unsupported_svcs.is_empty() {
                let _ = writeln!(o, "- unsupported svc: {}", c.unsupported_svcs.iter().map(|n| format!("{n:#x}")).collect::<Vec<_>>().join(", "));
            }
            if !c.missing_ipc.is_empty() {
                let _ = writeln!(o, "- missing IPC services/commands: {}", c.missing_ipc.iter().map(|s| format!("`{s}`")).collect::<Vec<_>>().join(", "));
            }
            if !c.missing_nvn.is_empty() {
                let _ = writeln!(o, "- missing NVN functions: {}", c.missing_nvn.iter().map(|s| format!("`{s}`")).collect::<Vec<_>>().join(", "));
            }
            for k in &c.crashes {
                let _ = writeln!(o, "- crash: signal {} at guest pc {} {}", k.signal, k.pc, esc(&k.note));
            }
            for f in &c.fps_notes {
                let _ = writeln!(o, "- fps: {}", esc(f));
            }
            let _ = writeln!(o);
        }
        if !v.notes.is_empty() {
            let _ = writeln!(o, "Notes:\n");
            for n in &v.notes {
                let _ = writeln!(o, "- {}", esc(n));
            }
            let _ = writeln!(o);
        }
    }
}

fn npdm(o: &mut String, p: &NpdmInfo) {
    let _ = writeln!(o, "NPDM (`main.npdm`, process `{}`):\n", p.name);
    let _ = writeln!(
        o,
        "- 64-bit: {}, address space type {}, main thread priority {} core {}, main stack {:#x}, system resource {:#x}, memory region {}, production ACID: {}",
        p.is_64bit, p.address_space, p.main_thread_priority, p.main_thread_core, p.main_thread_stack_size, p.system_resource_size, p.memory_region, p.production
    );
    let _ = writeln!(
        o,
        "- kernel: version {}, handle table {}, threads {}, debug flags {}, FS permissions {}",
        p.kernel_version.as_deref().unwrap_or("n/a"),
        p.handle_table_size.map_or("n/a".into(), |n| n.to_string()),
        p.thread_info.as_deref().unwrap_or("n/a"),
        p.debug_flags,
        p.fs_permissions
    );
    if !p.memory_maps.is_empty() || !p.io_maps.is_empty() {
        let _ = writeln!(o, "- mappings: {} memory, {} IO ({})", p.memory_maps.len(), p.io_maps.len(), p.memory_maps.iter().chain(&p.io_maps).cloned().collect::<Vec<_>>().join(", "));
    }
    let _ = writeln!(o, "- allowed SVCs ({}): {}", p.allowed_svcs.len(), p.allowed_svcs.iter().map(|n| format!("{n:#x}")).collect::<Vec<_>>().join(" "));
    let _ = writeln!(o, "- services used ({}): {}", p.services_used.len(), p.services_used.iter().map(|s| format!("`{s}`")).collect::<Vec<_>>().join(", "));
    if !p.services_hosted.is_empty() {
        let _ = writeln!(o, "- services hosted ({}): {}", p.services_hosted.len(), p.services_hosted.iter().map(|s| format!("`{s}`")).collect::<Vec<_>>().join(", "));
    }
    let _ = writeln!(o);
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn renders_table_symbols_and_blockers() {
        let mut m = Matrix::new();
        let g = m.game_mut("0100000000010000");
        g.name = "A|B".into();
        let v = g.version_mut(0, "0123456789abcdef0123");
        v.kind = "base".into();
        v.stages.insert("ingest".into(), StageResult { status: Status::Pass, ..Default::default() });
        v.stages.insert(
            "video".into(),
            StageResult { status: Status::Blocked, reason: "no NVN".into(), evidence: "work/x.log".into(), counters: Counters { missing_nvn: vec!["nvnQueueInit".into()], ..Default::default() }, ..Default::default() },
        );
        let t = render(&m);
        assert!(t.contains("A\\|B (0100000000010000)"));
        assert!(t.contains("| OK |"));
        assert!(t.contains("`video`: blocked - no NVN (evidence: `work/x.log`)"));
        assert!(t.contains("nvnQueueInit"));
        assert_eq!(t, render(&m));
        assert!(t.contains("`0123456789abcdef`"));
    }
}
