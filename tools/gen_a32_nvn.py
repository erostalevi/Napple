#!/usr/bin/env python3
"""Generates runtime/src/a32/a32_nvn_sigs.inc: one row per NVN entry point (name, return kind, argument kinds) from gfx/src/nvnapi/nvn_protos.h,
for the AArch32 import marshaller (runtime/src/a32/a32_hle.c). Kinds: v void, i 32-bit value, z size_t (zero-extended), Z ptrdiff_t (sign-extended),
p pointer (guest address, +window base), q 64-bit value, f float, c callback (guest function pointer: not callable from the host, passed as NULL).
Run: python3 tools/gen_a32_nvn.py > runtime/src/a32/a32_nvn_sigs.inc"""
import re, sys
txt = open("gfx/src/nvnapi/nvn_protos.h").read()
Q = {"uint64_t", "int64_t", "NVNbufferAddress", "NVNtextureHandle", "NVNimageHandle", "NVNcommandHandle", "NVNtextureAddress"}
def kind(t, ret=False):
    t = re.sub(r"\bconst\b", "", t).strip()
    t = re.sub(r"\s+[A-Za-z_]\w*$", "", t) if not ret and re.search(r"[A-Za-z_]\w*$", t) and t.split()[-1] not in Q and len(t.split()) > 1 and "*" not in t else t
    t = t.strip()
    if t == "void" and ret: return "v"
    if t.startswith("PFN") and "CALLBACK" in t: return "c"
    if t == "PFNNVNGENERICFUNCPTRPROC": return "p"
    if "*" in t or t.startswith("PFN") or t == "NVNnativeWindow": return "p"
    if t in Q: return "q"
    if t == "float": return "f"
    if t == "size_t": return "z"
    if t == "ptrdiff_t": return "Z"
    return "i"
rows = []
for m in re.finditer(r"typedef\s+(.+?)\s*\(\*NVNT_(\w+)\)\((.*?)\);", txt):
    r, name, args = m.groups()
    ks = ""
    for a in args.split(","):
        a = a.strip()
        if a in ("", "void"): continue
        ks += kind(a)
    rows.append((name, kind(r, True), ks))
print("/* generated by tools/gen_a32_nvn.py from gfx/src/nvnapi/nvn_protos.h: do not edit */")
for name, r, a in rows:
    print('{ "%s", \'%s\', "%s" },' % (name, r, a))
sys.stderr.write("%d functions, max args %d, callbacks in: %s\n" % (len(rows), max(len(a) for _, _, a in rows), [n for n, _, a in rows if "c" in a]))
